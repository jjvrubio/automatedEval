import { chromium } from "/Applications/Codex.app/Contents/Resources/cua_node/lib/node_modules/playwright-core/index.mjs";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import assert from "node:assert/strict";

const out = join(dirname(fileURLToPath(import.meta.url)), process.argv[2] ?? "browser-final");
await mkdir(out, { recursive: true });
const report = { tool: "Standalone Playwright + installed Edge; isolated temporary profile", phases: [], surfaces: [], pageErrors: [], consoleErrors: [], externalRequests: [], status: "RUNNING" };
const browser = await chromium.launch({ executablePath: "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 960 }, locale: "es-ES" });
  page.on("pageerror", e => report.pageErrors.push(String(e)));
  page.on("console", e => { if (e.type() === "error") report.consoleErrors.push(e.text()); });
  await page.route("**/*", route => {
    if (!["127.0.0.1", "localhost"].includes(new URL(route.request().url()).hostname)) {
      report.externalRequests.push(route.request().url()); return route.abort();
    }
    return route.continue();
  });
  let scope = page;
  const button = name => scope.getByRole("button", { name, exact: true });
  const heading = name => scope.getByRole("heading", { name, exact: true });
  const text = async () => scope.locator(".sports-shell").innerText();
  const state = () => scope.locator(".sports-shell").evaluate(el => ({
    text: el.textContent.replace(/\s+/g, " "),
    fields: [...el.querySelectorAll("input, select")].map(i => ({ name: i.name, value: i.value, checked: i.checked })),
  }));
  const record = async (phase, selector) => {
    await scope.locator("html").evaluate(() => document.fonts.ready);
    const overflow = await scope.locator("html").evaluate(el => el.scrollWidth > innerWidth);
    assert.equal(overflow, false, phase + " horizontal overflow");
    report.phases.push({ phase, text: await text(), horizontalOverflow: overflow });
    if (selector === "phone") await page.locator(".iphone-device").screenshot({ path: join(out, phase + ".png") });
    else if (selector) await scope.locator(selector).screenshot({ path: join(out, phase + ".png") });
  };
  const surface = async target => {
    const before = await state();
    await page.getByRole("link", { name: target === "app" ? "Ver como App" : "Ver como Web", exact: true }).click();
    scope = target === "app" ? page.frameLocator("iframe") : page;
    await scope.locator(".sports-shell").waitFor();
    assert.deepEqual(await state(), before, "same shared state and drafts");
    report.surfaces.push({ target, identical: true });
  };
  const assertIncludes = async values => { const visible = await text(); for (const value of values) assert.ok(visible.includes(value), value); };
  const confirm = async () => { await button("Confirmar inscripción").click(); await heading("Inscripción confirmada").waitFor(); };
  const complete = async effort => {
    await button("Simular check-in").click();
    await scope.getByText("Check-in simulado registrado. No acredita asistencia física real.", { exact: true }).waitFor();
    await scope.getByRole("radio", { name: effort, exact: true }).check();
    await button("Registrar esfuerzo").click();
    await heading("Primeros kilómetros").waitFor();
  };
  await page.goto("http://127.0.0.1:4173/?demo=sports-season-running");
  await heading("¿Con quién quieres probar la demo?").waitFor();
  await record("initial-people", ".sports-user-section");
  await assertIncludes(["P01", "P02", "P03", "No cliente"]);
  await button("Elegir a Lea Martín").click();
  await heading("511 puntos potenciales").waitFor();
  assert.equal(await scope.locator(".sports-purchases li").count(), 8);
  await assertIncludes(["511,75", "Active", "No pertenece al programa", "Sin saldo de puntos ni nivel asignado", "Simulación"]);
  await record("p01-commerce-counterfactual", ".sports-person-summary");
  await button("Leer QR de inscripción").click();
  await assertIncludes(["Cliente reconocido"]);
  assert.equal(await scope.locator('input[type="text"]').count(), 0);
  await button("Participar").click();
  await heading("Equipamiento para Carrera").waitFor();
  assert.equal(await scope.locator(".sports-equipment-grid article").count(), 4);
  await record("p01-equipment", ".sports-equipment");
  await scope.getByRole("radio", { name: /^Social/ }).check();
  await surface("app");
  await confirm();
  await record("p01-app-registration");
  await scope.getByLabel("Frecuencia de práctica (opcional)").selectOption("weekly");
  await scope.getByLabel("Objetivo (opcional)").selectOption("habit");
  await surface("web");
  await button("Compartir información y obtener la guía").click();
  await heading("Guía de preparación para 5 km").waitFor();
  await scope.getByText("Abrir guía", { exact: true }).click();
  await record("p01-voluntary-incentive", ".sports-voluntary");
  await complete("Medio");
  await record("p01-earned-badge", ".sports-result");
  await button("Ver mi insignia en Self Service").click();
  await heading("Tu relación continúa.").waitFor();
  await assertIncludes(["511 puntos potenciales", "Active", "Sin saldo de puntos ni nivel asignado", "Sports Season · obtenida en esta sesión", "Completado"]);
  assert.equal(await scope.locator(".sports-badge-list li").count(), 1);
  assert.equal(await scope.locator(".sports-program").count(), 0);
  await record("p01-self-service", ".sports-self-service");
  await surface("app");
  await record("p01-self-service-app", "phone");
  await surface("web");
  await button("Volver a la temporada").click();
  await button("Elegir a Diego Vidal").click();
  await button("Self Service").click();
  await assertIncludes(["731 puntos · nivel Pro", "Constancia deportiva", "Explorador multideporte", "15% en equipamiento running seleccionado", "Vóley playa Sunset Session", "Inscrito"]);
  assert.equal(await scope.locator(".sports-news-grid article").count(), 3);
  assert.equal(await scope.locator(".sports-purchases li").count(), 8);
  assert.equal(await scope.locator(".sports-badge-list li").count(), 2);
  await record("p02-self-service-before", ".sports-self-service");
  await button("Volver a la temporada").click();
  await button("Leer QR de inscripción").click();
  await assertIncludes(["Cliente reconocido"]);
  await button("Participar").click();
  await scope.getByRole("radio", { name: /^Bienestar/ }).check();
  await confirm();
  await button("Continuar sin aportar información").click();
  await record("p02-optional-skipped");
  await complete("Intenso");
  await button("Ver mi insignia en Self Service").click();
  await assertIncludes(["731 puntos · nivel Pro", "Sports Season · obtenida en esta sesión", "Completado"]);
  assert.equal(await scope.locator(".sports-badge-list li").count(), 3);
  await record("p02-self-service-new-badge", ".sports-self-service");
  await surface("app");
  await record("p02-self-service-app", "phone");
  await surface("web");
  await button("Volver a la temporada").click();
  await button("Elegir a Lea Martín").click();
  await button("Self Service").click();
  assert.equal(await scope.locator(".sports-badge-list li").count(), 1);
  await assertIncludes(["Sports Season · obtenida en esta sesión"]);
  await record("p01-restored-after-p02");
  await button("Reiniciar demo").click();
  await button("Elegir a Lea Martín").click();
  await button("No participar, pero quiero recibir información").click();
  await scope.getByRole("checkbox", { name: "Carrera", exact: true }).check();
  await scope.getByRole("checkbox", { name: "Sesiones de mejora", exact: true }).check();
  await surface("app");
  await button("Registrar intereses").click();
  await heading("Interés declarado registrado").waitFor();
  await record("information-declared", ".sports-interest-panel");
  assert.equal(await scope.locator(".sports-journey").count(), 0);
  await button("Self Service").click();
  assert.equal(await scope.locator(".sports-badge-list li").count(), 0);
  await assertIncludes(["Intereses: Carrera · Sesiones de mejora", "No tienes cupones asignados"]);
  await record("information-self-service-app", "phone");
  await surface("web");
  await button("Reiniciar demo").click();
  await button("Leer QR de inscripción").click();
  await button("Elegir a Persona sin identificar").click();
  await assertIncludes(["Persona no reconocida"]);
  await button("Participar").click();
  await scope.getByLabel("Nombre ficticio para esta demo").fill("Alex Demo");
  await button("Continuar con este nombre").click();
  await assertIncludes(["Sigues sin ser cliente ni miembro"]);
  await scope.getByRole("radio", { name: /^Social/ }).check();
  await confirm();
  await button("Continuar sin aportar información").click();
  await complete("Suave");
  await button("Ver mi insignia en Self Service").click();
  await assertIncludes(["Alex Demo", "No cliente", "No miembro", "Sin compras previas", "Sports Season · obtenida en esta sesión"]);
  await page.setViewportSize({ width: 390, height: 844 });
  await record("p03-self-service-narrow-web", ".sports-self-service");
  assert.deepEqual(report.pageErrors, []);
  assert.deepEqual(report.consoleErrors, []);
  assert.deepEqual(report.externalRequests, []);
  report.status = "PASS";
} catch (error) {
  report.status = "FAIL"; report.failure = String(error); throw error;
} finally {
  await writeFile(join(out, "report.json"), JSON.stringify(report, null, 2) + "\n");
  await browser.close();
  console.log(JSON.stringify({ status: report.status, phases: report.phases.length, surfaces: report.surfaces.length, failure: report.failure }));
}
