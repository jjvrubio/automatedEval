import { chromium } from "/Applications/Codex.app/Contents/Resources/cua_node/lib/node_modules/playwright-core/index.mjs";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import assert from "node:assert/strict";

const out = join(dirname(fileURLToPath(import.meta.url)), process.argv[2]);
await mkdir(out);
const report = { tool: "Standalone Playwright + installed Edge, headless, temporary profile", phases: [], surfaceComparisons: [], pageErrors: [], consoleErrors: [], humanUXAcceptance: "NOT EXECUTED" };
const browser = await chromium.launch({ executablePath: "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 }, locale: "es-ES" });
  page.on("pageerror", e => report.pageErrors.push(String(e)));
  page.on("console", e => { if (e.type() === "error") report.consoleErrors.push(e.text()); });
  let scope = page;
  const button = (name) => scope.getByRole("button", { name, exact: true });
  const heading = (name) => scope.getByRole("heading", { name, exact: true });
  const state = async () => scope.locator(".sports-shell").evaluate(el => ({
    // Compare rendered content independently of responsive visibility (e.g. the discipline count).
    // Native disclosure/scroll position is presentation state; all form drafts are checked separately.
    text: el.textContent.replace(/\s+/g, " "),
    fields: [...el.querySelectorAll("input, select")].map(item => ({ name: item.name, type: item.type, value: item.value, checked: item.checked })),
  }));
  const record = async (phase, capture) => {
    await scope.locator("html").evaluate(() => document.fonts.ready);
    const overflow = await scope.locator("html").evaluate(el => el.scrollWidth > innerWidth);
    assert.equal(overflow, false, phase + " horizontal overflow");
    const dimensions = await scope.locator("html").evaluate(() => ({ width: innerWidth, height: innerHeight }));
    report.phases.push({ phase, dimensions, url: page.url(), ...await state(), horizontalOverflow: overflow });
    if (capture === "phone") await page.locator(".iphone-device").screenshot({ path: join(out, phase + ".png") });
    else if (capture) await scope.locator(capture).screenshot({ path: join(out, phase + ".png") });
  };
  const switchSurface = async (surface, phase) => {
    const before = await state();
    await page.getByRole("link", { name: surface === "app" ? "Ver como App" : "Ver como Web", exact: true }).click();
    scope = surface === "app" ? page.frameLocator("iframe") : page;
    await scope.locator(".sports-shell").waitFor();
    assert.deepEqual(await state(), before, phase + " same rendered state and drafts");
    report.surfaceComparisons.push({ phase, to: surface, identical: true });
    await record(phase);
  };
  const effort = async (level) => {
    await button("Simular check-in").click();
    await scope.getByText("Check-in simulado registrado. No acredita asistencia física real.", { exact: true }).waitFor();
    await scope.getByRole("radio", { name: level, exact: true }).check();
    await button("Registrar esfuerzo").click();
    await heading("Primeros kilómetros").waitFor();
  };

  await page.goto("http://127.0.0.1:4173/?demo=sports-season-running");
  await heading("¿Con quién quieres probar la demo?").waitFor();
  await record("desktop-initial", ".sports-shell");
  await button("Leer QR de inscripción").click();
  await heading("QR de inscripción · simulado").waitFor();
  await record("registration-qr-entry", ".sports-entry-status");
  await button("Elegir a Lea Martín").click();
  await heading("194 puntos potenciales").waitFor();
  assert.equal(await scope.locator('input[type="text"]').count(), 0);
  await record("known-customer-counterfactual", ".sports-person-summary");
  await button("Participar").click();
  await heading("Equipamiento para Carrera").waitFor();
  await record("equipment", ".sports-equipment");
  await button("Confirmar inscripción").click();
  await scope.getByRole("alert").filter({ hasText: "Elige Social o Bienestar" }).waitFor();
  await record("registration-error", ".sports-journey");
  await scope.getByRole("radio", { name: /^Bienestar/ }).check();
  await switchSurface("app", "draft-modality-web-to-app");
  await button("Confirmar inscripción").click();
  await heading("Inscripción confirmada").waitFor();
  await record("app-registration");
  await scope.getByLabel("Frecuencia de práctica (opcional)").selectOption("weekly");
  await scope.getByLabel("Objetivo (opcional)").selectOption("habit");
  await switchSurface("web", "draft-voluntary-app-to-web");
  await button("Compartir información y obtener la guía").click();
  await heading("Guía de preparación para 5 km").waitFor();
  await scope.getByText("Abrir guía", { exact: true }).click();
  await record("voluntary-incentive", ".sports-voluntary");
  await switchSurface("app", "registered-and-incentive-web-to-app");
  await button("Simular check-in").click();
  await button("Registrar esfuerzo").click();
  await scope.getByRole("alert").filter({ hasText: "Elige un esfuerzo" }).waitFor();
  await record("app-effort-error", ".sports-error");
  await scope.getByRole("radio", { name: "Intenso", exact: true }).check();
  await button("Registrar esfuerzo").click();
  await heading("Primeros kilómetros").waitFor();
  await record("app-badge", ".sports-result");
  await button("Conocer Club Brisa").click();
  await scope.getByText(/sigues siendo participante externo/).waitFor();
  await record("app-invitation", ".sports-club-info");
  await switchSurface("web", "badge-and-invitation-app-to-web");
  await button("Marketing / CRM").click();
  await heading("La participación, con contexto.").waitFor();
  const crm = await scope.locator("#sports-main").innerText();
  for (const text of ["Cliente conocido", "Externo · no pertenece al club", "simulated-check-in", "participant-self-report", "Primeros kilómetros"]) assert.ok(crm.includes(text), text);
  await record("crm-primary-compatibility", ".sports-crm-grid");
  await button("Participante").click();
  await heading("194 puntos potenciales").waitFor();
  await record("return-primary");
  await button("Reiniciar demo").click();
  assert.equal(await heading("194 puntos potenciales").count(), 0);
  await record("reset-primary");

  await button("Elegir a Diego Vidal").click();
  await heading("860 puntos · nivel Activo").waitFor();
  assert.equal(await scope.locator(".sports-counterfactual").count(), 0);
  await record("member-contrast", ".sports-person-summary");
  await button("No participar, pero quiero recibir información").click();
  await button("Registrar intereses").click();
  await scope.getByRole("alert").filter({ hasText: "Elige al menos un interés" }).waitFor();
  await record("interests-error", ".sports-error");
  await scope.getByRole("checkbox", { name: "Vela", exact: true }).check();
  await scope.getByRole("checkbox", { name: "Próximas convocatorias", exact: true }).check();
  await button("Registrar intereses").click();
  await heading("Interés declarado registrado").waitFor();
  assert.equal(await button("Confirmar inscripción").count(), 0);
  assert.equal(await scope.locator(".sports-result").count(), 0);
  await record("declared-interests", ".sports-interest-panel");
  await switchSurface("app", "declared-interests-web-to-app");
  await scope.getByRole("checkbox", { name: "Carrera", exact: true }).check();
  await button("Registrar intereses").click();
  await switchSurface("web", "updated-interests-app-to-web");
  await button("Reiniciar demo").click();
  await button("Elegir a Diego Vidal").click();
  await button("Participar").click();
  await button("Elegir Carrera").click();
  await scope.getByRole("radio", { name: /^Social/ }).check();
  await button("Confirmar inscripción").click();
  await button("Continuar sin aportar información").click();
  await effort("Medio");
  await heading("860 puntos · nivel Activo").waitFor();
  assert.equal(await button("Conocer Club Brisa").count(), 0);
  await record("member-badge-without-new-membership", ".sports-result");
  await button("Marketing / CRM").click();
  await scope.getByText("Miembro del club", { exact: true }).waitFor();
  await scope.getByText("Ya pertenece al club. Esta participación no genera una invitación de alta.", { exact: true }).waitFor();
  await record("member-crm-compatibility", ".sports-crm-grid");
  await button("Reiniciar demo").click();
  await heading("¿Con quién quieres probar la demo?").waitFor();

  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("http://127.0.0.1:4173/showcase?demo=sports-season-running");
  scope = page.frameLocator("iframe");
  await heading("¿Con quién quieres probar la demo?").waitFor();
  await record("mobile-app-initial", "phone");
  await button("Leer QR de inscripción").click();
  await button("Elegir a Persona sin identificar").click();
  await button("Participar").click();
  await heading("Datos mínimos para la inscripción").waitFor();
  await record("unknown-minimum-form", ".sports-visitor");
  await scope.getByRole("radio", { name: /^Social/ }).check();
  await button("Confirmar inscripción").click();
  await scope.getByRole("alert").filter({ hasText: "Indica un nombre ficticio" }).waitFor();
  await record("unknown-required-name-error", ".sports-error");
  await scope.getByLabel("Nombre ficticio para esta demo").fill("Alex Prueba");
  await button("Continuar con este nombre").click();
  await heading("Alex Prueba").waitFor();
  await button("Confirmar inscripción").click();
  await button("Compartir información y obtener la guía").click();
  await scope.getByRole("alert").filter({ hasText: "Selecciona al menos una respuesta" }).waitFor();
  await record("voluntary-empty-error", ".sports-error");
  await button("Continuar sin aportar información").click();
  assert.equal(await scope.locator(".sports-incentive").count(), 0);
  await effort("Suave");
  await record("unknown-participant-badge", ".sports-result");
  await button("Marketing / CRM").click();
  await scope.getByText("No establecida", { exact: true }).waitFor();
  await scope.getByText("Externo · no pertenece al club", { exact: true }).waitFor();
  await record("unknown-remains-noncustomer");
  await button("Reiniciar demo").click();
  await heading("¿Con quién quieres probar la demo?").waitFor();
  assert.equal(await heading("Alex Prueba").count(), 0);
  await record("mobile-app-reset");
  assert.deepEqual(report.pageErrors, []);
  assert.deepEqual(report.consoleErrors, []);
  report.status = "PASS";
} catch (error) {
  report.status = "FAIL";
  report.error = String(error.stack ?? error);
  process.exitCode = 1;
} finally {
  await browser.close();
  await writeFile(join(out, "report.json"), JSON.stringify(report, null, 2) + "\n");
  console.log(JSON.stringify({ status: report.status, phases: report.phases.length, surfaceComparisons: report.surfaceComparisons.length, error: report.error, output: out }));
}
